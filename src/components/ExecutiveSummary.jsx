import React, { useState } from 'react';
import { CheckCircle2, AlertCircle, FileText, Copy, Check, Printer, Sparkles, HeartHandshake, ShieldCheck } from 'lucide-react';

export function ExecutiveSummary({
  patient,
  biomarkers,
  diagnosticFindings,
  overallIndex,
  clinicalSummary,
  onPrint,
  t
}) {
  const [copied, setCopied] = useState(false);

  const safeBiomarkers = Array.isArray(biomarkers) ? biomarkers : [];
  const normalMarkers = safeBiomarkers.filter(b => b.status === 'NORMAL');
  const attentionMarkers = safeBiomarkers.filter(b => b.status !== 'NORMAL');
  const normalCount = normalMarkers.length;
  const attentionCount = attentionMarkers.length;

  const patientName = patient?.name || 'Patient';
  const reportDate = patient?.reportDate || 'Recent';
  const patientId = patient?.patientId || 'N/A';

  const handleCopySummary = () => {
    const textLines = [
      `HEALTH SUMMARY: ${patientName}`,
      `Report Date: ${reportDate} | ID: ${patientId}`,
      `Overall Health Index: ${overallIndex || 85}/100`,
      '',
      `1. WHAT IS NORMAL & HEALTHY:`,
      ...normalMarkers.map(b => `  • ${b.name}: ${b.value} ${b.unit} (Normal Range: ${b.optimalRange[0]}-${b.optimalRange[1]} ${b.unit})`),
      '',
      `2. VALUES NEEDING DOCTOR REVIEW:`,
      ...(attentionMarkers.length > 0 
        ? attentionMarkers.map(b => `  • ${b.name}: ${b.value} ${b.unit} [${b.status}] (Normal Range: ${b.optimalRange[0]}-${b.optimalRange[1]} ${b.unit}) - ${b.clinicalNote}`)
        : ['  • All tested biomarkers are within standard reference intervals!']),
      ...(diagnosticFindings?.items?.length ? [
        '',
        `3. DIAGNOSTIC / IMAGING FINDINGS:`,
        ...diagnosticFindings.items.map(item => `  • ${item}`)
      ] : []),
      '',
      `CLINICAL SYNTHESIS:`,
      clinicalSummary,
      '',
      `Generated by AI Health Interpreter (For informational literacy; consult your doctor for medical advice).`
    ];

    navigator.clipboard.writeText(textLines.join('\n')).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    });
  };

  return (
    <div className="bg-white rounded-3xl p-6 sm:p-8 border border-slate-200 shadow-sm mb-8 relative overflow-hidden">
      
      {/* Top Banner */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-6 border-b border-slate-200">
        <div>
          <div className="flex items-center space-x-2 text-xs font-bold text-clinical-600 uppercase tracking-wider mb-1">
            <Sparkles className="w-4 h-4 text-clinical-500" />
            <span>Executive Health Summary &amp; Key Insights</span>
          </div>
          <h3 className="text-xl sm:text-2xl font-extrabold text-slate-900 tracking-tight">
            Comprehensive Findings for {patientName}
          </h3>
          <p className="text-xs text-slate-500 mt-1">
            Clear, non-technical translation of your report results for peace of mind and doctor consultation.
          </p>
        </div>

        {/* Action Buttons: Copy & Print */}
        <div className="flex items-center space-x-2.5 shrink-0 no-print">
          <button
            onClick={handleCopySummary}
            className={`flex items-center space-x-1.5 px-3.5 py-2.5 rounded-xl text-xs font-bold transition-all border cursor-pointer ${
              copied
                ? 'bg-emerald-50 text-emerald-800 border-emerald-300'
                : 'bg-slate-100 hover:bg-slate-200 text-slate-700 border-slate-200'
            }`}
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-600" />
                <span>Summary Copied!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5 text-slate-500" />
                <span>Copy Summary</span>
              </>
            )}
          </button>

          {onPrint && (
            <button
              onClick={onPrint}
              className="flex items-center space-x-1.5 px-3.5 py-2.5 rounded-xl text-xs font-bold bg-clinical-50 text-clinical-700 hover:bg-clinical-100 border border-clinical-200 transition-colors cursor-pointer"
            >
              <Printer className="w-3.5 h-3.5 text-clinical-600" />
              <span>Print Report</span>
            </button>
          )}
        </div>
      </div>

      {/* Grid: What is Good vs What Needs Attention */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6 my-6">
        
        {/* Good & Balanced Findings */}
        <div className="p-5 rounded-2xl bg-emerald-50/50 border border-emerald-200/80">
          <div className="flex items-center space-x-2 text-xs font-bold text-emerald-800 uppercase tracking-wider mb-3">
            <CheckCircle2 className="w-4 h-4 text-emerald-600" />
            <span>Normal &amp; Healthy ({normalCount} Tests)</span>
          </div>
          {normalMarkers.length > 0 ? (
            <ul className="space-y-2.5">
              {normalMarkers.map(b => (
                <li key={b.id} className="text-xs text-slate-700 flex items-start space-x-2">
                  <span className="w-1.5 h-1.5 rounded-full bg-emerald-500 mt-1.5 shrink-0" />
                  <div>
                    <strong className="text-slate-900 font-semibold">{b.name}</strong>:{' '}
                    <span className="font-mono font-bold text-emerald-800">{b.value} {b.unit}</span>{' '}
                    <span className="text-[11px] text-slate-500">(Ref: {b.optimalRange[0]}–{b.optimalRange[1]} {b.unit})</span>
                    <div className="text-[11px] text-emerald-700 font-medium mt-0.5">
                      ✓ Operating within standard reference intervals.
                    </div>
                  </div>
                </li>
              ))}
            </ul>
          ) : (
            <p className="text-xs text-slate-500 italic">No normal markers identified in current panel.</p>
          )}
        </div>

        {/* Needs Doctor Attention */}
        <div className="p-5 rounded-2xl bg-amber-50/50 border border-amber-200/80">
          <div className="flex items-center space-x-2 text-xs font-bold text-amber-800 uppercase tracking-wider mb-3">
            <AlertCircle className="w-4 h-4 text-amber-600" />
            <span>Values to Discuss with Doctor ({attentionMarkers.length} Tests)</span>
          </div>
          {attentionMarkers.length > 0 ? (
            <ul className="space-y-2.5">
              {attentionMarkers.map(b => (
                <li key={b.id} className="text-xs text-slate-700 flex items-start space-x-2">
                  <span className="w-1.5 h-1.5 rounded-full bg-amber-500 mt-1.5 shrink-0" />
                  <div>
                    <strong className="text-slate-900 font-semibold">{b.name}</strong>:{' '}
                    <span className="font-mono font-bold text-amber-900">{b.value} {b.unit}</span>{' '}
                    <span className="text-[11px] text-slate-500">(Ref: {b.optimalRange[0]}–{b.optimalRange[1]} {b.unit})</span>
                    <div className="text-[11px] text-amber-800 font-medium mt-0.5">
                      {b.clinicalNote}
                    </div>
                  </div>
                </li>
              ))}
            </ul>
          ) : (
            <div className="text-xs text-emerald-700 font-medium flex items-center space-x-2">
              <CheckCircle2 className="w-4 h-4 text-emerald-600" />
              <span>All detected biomarkers are within normal reference ranges!</span>
            </div>
          )}
        </div>

      </div>

      {/* Diagnostic & Imaging Findings (e.g. Ultrasound) if extracted */}
      {diagnosticFindings?.items?.length > 0 && (
        <div className="mb-6 p-5 rounded-2xl bg-slate-50 border border-slate-200">
          <div className="flex items-center space-x-2 text-xs font-bold text-slate-800 uppercase tracking-wider mb-2.5">
            <FileText className="w-4 h-4 text-clinical-600" />
            <span>{diagnosticFindings.title || 'Diagnostic & Imaging Findings (Ultrasound / Radiology)'}</span>
          </div>
          <ul className="space-y-1.5">
            {diagnosticFindings.items.map((item, idx) => (
              <li key={idx} className="text-xs text-slate-700 flex items-start space-x-2">
                <span className="text-clinical-600 font-bold">•</span>
                <span>{item}</span>
              </li>
            ))}
          </ul>
          <p className="text-[11px] text-slate-500 mt-3 pt-2 border-t border-slate-200">
            💡 Imaging findings should be evaluated alongside your blood work by your doctor.
          </p>
        </div>
      )}

      {/* Action Checklist for Consultation */}
      <div className="p-4 rounded-2xl bg-slate-100/70 border border-slate-200 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 text-xs text-slate-700">
        <div className="flex items-center space-x-2">
          <ShieldCheck className="w-4 h-4 text-clinical-600 shrink-0" />
          <span>
            <strong>Next Step:</strong> Review this summary with your attending physician. We have prepared personalized questions below to help guide your visit.
          </span>
        </div>
      </div>

    </div>
  );
}
